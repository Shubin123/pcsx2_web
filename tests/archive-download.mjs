import { test, afterEach } from 'node:test';
import assert from 'node:assert/strict';
import { once } from 'node:events';
import { createServer } from '../scripts/server.mjs';
import { fetchArchiveDownload } from '../web/archive-download.js';

const nativeFetch = globalThis.fetch;
afterEach(() => { globalThis.fetch = nativeFetch; });
const game = { name: 'Generated fixture (USA).iso', url: 'https://archive.org/download/playstation-2-games-iso/Generated%20fixture%20(USA).iso' };

test('direct success streams without using the relay', async () => {
  const body = new Response(new Uint8Array([1, 2, 3]));
  let calls = 0;
  globalThis.fetch = async url => { calls++; assert.equal(url, game.url); return body; };
  assert.equal(await fetchArchiveDownload(game), body);
  assert.equal(calls, 1);
});

test('CORS/network rejection falls back to a same-origin encoded filename', async () => {
  const signal = new AbortController().signal, calls = [], body = new Response('fixture');
  globalThis.fetch = async (url, options) => {
    calls.push(url); assert.equal(options.signal, signal);
    if (calls.length === 1) throw new TypeError('Failed to fetch');
    return body;
  };
  assert.equal(await fetchArchiveDownload(game, signal), body);
  assert.deepEqual(calls, [game.url, `./archive-download?file=${encodeURIComponent(game.name)}`]);
});

test('canceling a failed direct request never starts a relay', async () => {
  const controller = new AbortController(); let calls = 0;
  globalThis.fetch = async () => { calls++; controller.abort(); throw new TypeError('Failed to fetch'); };
  await assert.rejects(fetchArchiveDownload(game, controller.signal), { name: 'AbortError' });
  assert.equal(calls, 1);
});

test('HTTP failures are preserved without retrying another download', async () => {
  const response = new Response('denied', {status: 403}); let calls = 0;
  globalThis.fetch = async () => { calls++; return response; };
  assert.equal(await fetchArchiveDownload(game), response);
  assert.equal(calls, 1);
});

test('static hosts report the unavailable relay and release the error body', async () => {
  let calls = 0, canceled = false;
  globalThis.fetch = async () => {
    if (++calls === 1) throw new TypeError('Failed to fetch');
    return new Response(new ReadableStream({cancel() { canceled = true; }}), {status: 404});
  };
  await assert.rejects(fetchArchiveDownload(game), /this host has no download relay/);
  assert.equal(canceled, true);
});

test('relay network failure gives an actionable error', async () => {
  let calls = 0;
  globalThis.fetch = async () => { calls++; throw new TypeError('offline fixture'); };
  await assert.rejects(fetchArchiveDownload(game), /Retry or import a local file/);
  assert.equal(calls, 2);
});

test('canceling the relay preserves AbortError', async () => {
  const controller = new AbortController(); let calls = 0;
  globalThis.fetch = async () => {
    if (++calls === 2) controller.abort();
    throw new TypeError('blocked fixture');
  };
  await assert.rejects(fetchArchiveDownload(game, controller.signal), {name: 'AbortError'});
  assert.equal(calls, 2);
});

async function localRelay(t, upstream) {
  const server = createServer({fetchArchive: upstream});
  server.listen(0, '127.0.0.1'); await once(server, 'listening');
  t.after(async () => { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); });
  return `http://127.0.0.1:${server.address().port}/archive-download`;
}

test('relay streams generated bytes through permitted Archive redirects', async t => {
  const calls = [], fixture = Uint8Array.from([1, 2, 3, 4]);
  const base = await localRelay(t, async (url, options) => {
    calls.push(url); assert.equal(options.redirect, 'manual');
    if (calls.length === 1) return new Response(null, {status: 302, headers: {location: 'https://ia800000.us.archive.org/fixture.iso'}});
    return new Response(fixture, {headers: {'content-length': '4'}});
  });
  const response = await nativeFetch(`${base}?file=${encodeURIComponent(game.name)}`);
  assert.equal(response.status, 200);
  assert.equal(response.headers.get('cross-origin-embedder-policy'), 'require-corp');
  assert.deepEqual(new Uint8Array(await response.arrayBuffer()), fixture);
  assert.equal(calls[0], game.url);
  assert.equal(calls.length, 2);
});

test('relay rejects invalid filenames and unsupported methods before fetching', async t => {
  let calls = 0;
  const base = await localRelay(t, async () => { calls++; throw Error('Unexpected upstream call'); });
  for (const name of ['', '../fixture.iso', 'https://example.test/fixture.iso', 'fixture.zip', 'a\\b.iso', 'a\u0000.iso']) {
    const response = await nativeFetch(`${base}?file=${encodeURIComponent(name)}`);
    assert.equal(response.status, 400, name); await response.body.cancel();
  }
  assert.equal((await nativeFetch(`${base}?file=fixture.iso`, {method: 'POST'})).status, 405);
  assert.equal((await nativeFetch(`${base}?file=fixture.iso`, {method: 'HEAD'})).status, 405);
  assert.equal(calls, 0);
});

test('relay rejects redirects outside Archive before contacting another host', async t => {
  let calls = 0;
  const base = await localRelay(t, async () => { calls++; return new Response(null, {status: 302, headers: {location: 'https://archive.org.evil.test/fixture.iso'}}); });
  assert.equal((await nativeFetch(`${base}?file=fixture.iso`)).status, 502);
  assert.equal(calls, 1);
});

test('relay preserves upstream access failures and reports network failures', async t => {
  let fail = false;
  const base = await localRelay(t, async () => {
    if (fail) throw new TypeError('offline');
    return new Response('restricted', {status: 403});
  });
  assert.equal((await nativeFetch(`${base}?file=fixture.iso`)).status, 403);
  fail = true;
  assert.equal((await nativeFetch(`${base}?file=fixture.iso`)).status, 502);
});

test('relay bounds redirect loops', async t => {
  let calls = 0;
  const base = await localRelay(t, async () => {
    calls++;
    return new Response(null, {status: 302, headers: {location: 'https://archive.org/loop.iso'}});
  });
  assert.equal((await nativeFetch(`${base}?file=fixture.iso`)).status, 502);
  assert.equal(calls, 6);
});
